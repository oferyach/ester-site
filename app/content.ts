export type Book = {
  id: string;
  title: string;
  year: number;
  category: string;
  overview: string;
  context: string;
  themes: string[];
  palette: string;
  cover: string;
  coverNote?: string;
  review: string[];
};

type BookInput = Omit<Book, 'cover' | 'review'> & {
  reading: string;
  craft: string;
  legacy: string;
};

function createBook(input: BookInput): Book {
  const { reading, craft, legacy, ...book } = input;
  return {
    ...book,
    cover: `/assets/covers/${book.id}.jpg`,
    review: [book.overview, book.context, reading, craft, legacy],
  };
}

